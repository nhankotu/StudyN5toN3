// Convert kanji character to 5-digit hex string matching KanjiVG filenames
export function kanjiToHex(char) {
  if (!char) return '';
  const code = char.codePointAt(0);
  return '0' + code.toString(16).toLowerCase();
}

/**
 * Approximate parsing of SVG path data into an array of 2D points.
 * Handles M (move), L (line), C/S (cubic bezier), Q (quadratic), and relative equivalents.
 */
export function parseSvgPathToPoints(d, samplesPerCurve = 8) {
  const points = [];
  if (!d) return points;

  // Regex to match path command followed by numbers
  const cmdRegex = /([a-df-z])([^a-df-z]*)/gi;
  let match;
  let curX = 0;
  let curY = 0;

  while ((match = cmdRegex.exec(d)) !== null) {
    const cmd = match[1];
    const argsStr = match[2].trim();
    const args = argsStr.length ? argsStr.split(/[\s,]+|-/).filter(Boolean).map(Number) : [];
    const isRel = cmd === cmd.toLowerCase();
    const type = cmd.toUpperCase();

    if (type === 'M' && args.length >= 2) {
      curX = isRel ? curX + args[0] : args[0];
      curY = isRel ? curY + args[1] : args[1];
      points.push({ x: curX, y: curY });
    } else if (type === 'L' && args.length >= 2) {
      curX = isRel ? curX + args[0] : args[0];
      curY = isRel ? curY + args[1] : args[1];
      points.push({ x: curX, y: curY });
    } else if (type === 'C' && args.length >= 6) {
      const p0 = { x: curX, y: curY };
      const p1 = { x: isRel ? curX + args[0] : args[0], y: isRel ? curY + args[1] : args[1] };
      const p2 = { x: isRel ? curX + args[2] : args[2], y: isRel ? curY + args[3] : args[3] };
      const p3 = { x: isRel ? curX + args[4] : args[4], y: isRel ? curY + args[5] : args[5] };

      // Sample cubic bezier
      for (let i = 1; i <= samplesPerCurve; i++) {
        const t = i / samplesPerCurve;
        const mt = 1 - t;
        const x = mt * mt * mt * p0.x + 3 * mt * mt * t * p1.x + 3 * mt * t * t * p2.x + t * t * t * p3.x;
        const y = mt * mt * mt * p0.y + 3 * mt * mt * t * p1.y + 3 * mt * t * t * p2.y + t * t * t * p3.y;
        points.push({ x, y });
      }
      curX = p3.x;
      curY = p3.y;
    } else if (type === 'S' && args.length >= 4) {
      const p0 = { x: curX, y: curY };
      const p2 = { x: isRel ? curX + args[0] : args[0], y: isRel ? curY + args[1] : args[1] };
      const p3 = { x: isRel ? curX + args[2] : args[2], y: isRel ? curY + args[3] : args[3] };
      for (let i = 1; i <= samplesPerCurve; i++) {
        const t = i / samplesPerCurve;
        const mt = 1 - t;
        const x = mt * mt * p0.x + 2 * mt * t * p2.x + t * t * p3.x;
        const y = mt * mt * p0.y + 2 * mt * t * p2.y + t * t * p3.y;
        points.push({ x, y });
      }
      curX = p3.x;
      curY = p3.y;
    }
  }

  // Scale from KanjiVG 109x109 viewBox to 0-100 normalized space
  return points.map(p => ({
    x: (p.x / 109) * 100,
    y: (p.y / 109) * 100
  }));
}

