// Memory cache for dynamically fetched KanjiVG data
const kanjiCache = new Map();

/**
 * Returns stroke definitions for a kanji character as an array of stroke point paths (0-100 normalized).
 * Also attaches .strokes, .strokePaths, .strokeCount, and .svgContent.
 */
export async function getKanjiStrokes(char) {
  if (!char) return null;
  const singleChar = Array.from(char)[0];

  let strokeSvgList = null;

  // 1. Check pre-packaged data
  if (PREPACKAGED_KANJI[singleChar]) {
    strokeSvgList = PREPACKAGED_KANJI[singleChar];
  } else if (kanjiCache.has(singleChar)) {
    // 2. Check memory cache
    strokeSvgList = kanjiCache.get(singleChar);
  } else if (typeof fetch !== 'undefined') {
    // 3. Attempt CDN fetch
    const hex = kanjiToHex(singleChar);
    if (hex) {
      try {
        const url = 'https://cdn.jsdelivr.net/gh/KanjiVG/kanjivg/kanji/' + hex + '.svg';
        const res = await fetch(url, { cache: 'force-cache' });
        if (res.ok) {
          const svgText = await res.text();
          const pathMatches = svgText.matchAll(/<path[^>]*\sd="([^"]+)"/g);
          const list = [];
          for (const m of pathMatches) list.push(m[1]);
          if (list.length > 0) {
            strokeSvgList = list;
            kanjiCache.set(singleChar, strokeSvgList);
          }
        }
      } catch (e) {
        // network error / offline
      }
    }
  }

  if (!strokeSvgList || strokeSvgList.length === 0) {
    kanjiCache.set(singleChar, null);
    return null;
  }

  const strokes = strokeSvgList.map(d => parseSvgPathToPoints(d));
  strokes.strokes = strokes;
  strokes.strokePaths = strokeSvgList;
  strokes.strokeCount = strokeSvgList.length;
  strokes.svgContent = generateKanjiSvg(strokeSvgList);
  return strokes;
}
