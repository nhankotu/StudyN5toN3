// Memory cache for dynamically fetched KanjiVG data
const kanjiCache = new Map();

/**
 * Returns stroke definitions for a kanji character as an array of stroke point paths (0-100 normalized).
 * If prepackaged, returns immediately.
 * Otherwise attempts to fetch from KanjiVG CDN, or falls back to null.
 */
export async function getKanjiStrokes(char) {
  if (!char) return null;
  const singleChar = Array.from(char)[0];

  // 1. Check pre-packaged data
  if (PREPACKAGED_KANJI[singleChar]) {
    return PREPACKAGED_KANJI[singleChar].map(d => parseSvgPathToPoints(d));
  }

  // 2. Check memory cache
  if (kanjiCache.has(singleChar)) {
    return kanjiCache.get(singleChar);
  }

  // 3. Attempt CDN fetch (optional graceful enhancement)
  const hex = kanjiToHex(singleChar);
  if (!hex || typeof fetch === 'undefined') return null;

  try {
    const url = `https://cdn.jsdelivr.net/gh/KanjiVG/kanjivg/kanji/${hex}.svg`;
    const res = await fetch(url, { cache: 'force-cache' });
    if (!res.ok) {
      kanjiCache.set(singleChar, null);
      return null;
    }
    const svgText = await res.text();

    // Extract all <path ... d="..." /> attributes
    const pathMatches = svgText.matchAll(/<path[^>]*\sd="([^"]+)"/g);
    const strokeSvgList = [];
    for (const m of pathMatches) {
      strokeSvgList.push(m[1]);
    }

    if (strokeSvgList.length > 0) {
      const strokes = strokeSvgList.map(d => parseSvgPathToPoints(d));
      kanjiCache.set(singleChar, strokes);
      return strokes;
    }
  } catch (err) {
    // Network unavailable or offline
  }

  kanjiCache.set(singleChar, null);
  return null;
}
